"""
Доля приходов (выручки) по социальным услугам — для распределения косвенных расходов на соцтакси.

Коэффициент задаётся по данным учёта / сводных отчётов по приходам (не из счёта 62).
"""

from __future__ import annotations

# Доля приходов по соцуслугам (соцтакси) в общем объёме приходов организации, год → k
SOC_TAXI_SHARE: dict[int, float] = {
    2024: 0.78,
    2025: 0.76,
}


def get_soc_taxi_share(year: int) -> float:
    """Возвращает k для умножения косвенных расходов (коммуналка, IT, проч.)."""
    try:
        return SOC_TAXI_SHARE[year]
    except KeyError as e:
        raise ValueError(f"Нет коэффициента доли соцуслуг для года {year}") from e
